"""diag_qa026.py — верификация фикса qa_026."""
from text_to_prolog import TextToProlog

t = TextToProlog()

for q in [
    "В какой стране находится технопарк Казань?",
    "В какой стране находится технопарк Саратов?",
    "В какой стране находится технопарк Москва?",
    "Кто директор технопарка Саратов?",
    "Когда основан технопарк Саратов?",
    "Где находится технопарк Саратов?",
]:
    _, query = t.parse(
        q, strict=True, facts_from_questions=False,
    )
    print(f"{q[:55]:57} → {query!r}")